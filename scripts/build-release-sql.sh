#!/usr/bin/env bash
# Generates the production release files from the reviewed migrations:
#   supabase/release/step_a_apply.sql = 20261117000100 + 20261117000200
#   supabase/release/step_b_apply.sql = 20261118000100 + 20261118000200
# Each file is pure SQL (no psql meta-commands), runs as ONE transaction, and
# checks preconditions before and postconditions after the migrations; any
# failed check raises an exception, so the whole step rolls back.
# CI regenerates these files and fails if the committed copies differ.
set -euo pipefail
cd "$(dirname "$0")/.."
M=supabase/migrations
OUT=supabase/release

emit() { # $1 = migration file
  printf '\n-- ===== begin %s =====\n' "$(basename "$1")"
  cat "$1"
  printf '\n-- ===== end %s =====\n' "$(basename "$1")"
}

{
cat <<'SQL'
-- STEP A — Akure Humboldt Kolleg 2027 release (GENERATED by scripts/build-release-sql.sh; do not edit)
-- Applies 20261117000100 (no-op on live) and 20261117000200 (additive; compatible
-- with the currently deployed app). One transaction: any failed check rolls back.
begin;

-- Snapshot the state that must not change.
create temporary table _release_pre on commit drop as
select s.demo_mode, s.registration_open, s.submissions_open, s.registration_deadline, s.abstract_deadline,
       (select count(*) from public.registrations) as registrations,
       (select count(*) from public.abstracts) as abstracts,
       (select count(*) from public.reviews) as reviews,
       (select count(*) from public.user_roles) as user_roles
from public.conference_settings s where s.id = 1;

do $pre$ begin
  if not (select demo_mode from _release_pre) then
    raise exception 'STEP A precondition failed: demo_mode must be true (pre-launch test mode)';
  end if;
  if to_regprocedure('public.find_conference_account(text)') is null
     or to_regprocedure('public.conference_reviewer_directory()') is null then
    raise exception 'STEP A precondition failed: the two live organiser functions are missing; run the drift check';
  end if;
end $pre$;
SQL
emit $M/20261117000100_reconcile_reviewer_directory_functions.sql
emit $M/20261117000200_reviewer_admin_and_launch_controls.sql
cat <<'SQL'

do $post$ declare p record; begin
  select * into p from _release_pre;
  if (select (demo_mode, registration_open, submissions_open, registration_deadline, abstract_deadline)
             is distinct from (p.demo_mode, p.registration_open, p.submissions_open, p.registration_deadline, p.abstract_deadline)
      from public.conference_settings where id = 1) then
    raise exception 'STEP A postcondition failed: launch settings changed';
  end if;
  if (select count(*) from public.registrations) <> p.registrations or (select count(*) from public.abstracts) <> p.abstracts
     or (select count(*) from public.reviews) <> p.reviews or (select count(*) from public.user_roles) <> p.user_roles then
    raise exception 'STEP A postcondition failed: row counts changed';
  end if;
  if to_regprocedure('public.grant_conference_reviewer(text)') is null or to_regprocedure('public.revoke_conference_reviewer(uuid)') is null then
    raise exception 'STEP A postcondition failed: reviewer administration functions not created';
  end if;
  if has_function_privilege('anon', 'public.grant_conference_reviewer(text)', 'EXECUTE')
     or has_function_privilege('anon', 'public.revoke_conference_reviewer(uuid)', 'EXECUTE') then
    raise exception 'STEP A postcondition failed: anon can execute reviewer administration';
  end if;
  raise notice 'STEP A verified: settings and row counts unchanged; reviewer administration functions present and closed to anon';
end $post$;
commit;
SQL
} > $OUT/step_a_apply.sql

{
cat <<'SQL'
-- STEP B — Akure Humboldt Kolleg 2027 release (GENERATED by scripts/build-release-sql.sh; do not edit)
-- Applies 20261118000100 (blind review) and 20261118000200 (least privilege).
-- NOT compatible with the previously deployed app: promote the new deployment
-- immediately after COMMIT. One transaction: any failed check rolls back.
begin;

create temporary table _release_pre on commit drop as
select s.demo_mode, s.registration_open, s.submissions_open, s.registration_deadline, s.abstract_deadline,
       (select count(*) from public.registrations) as registrations,
       (select count(*) from public.abstracts) as abstracts,
       (select count(*) from public.reviews) as reviews,
       (select count(*) from public.review_assignments) as assignments,
       (select count(*) from public.user_roles) as user_roles
from public.conference_settings s where s.id = 1;

do $pre$ begin
  if not (select demo_mode from _release_pre) then
    raise exception 'STEP B precondition failed: demo_mode must be true (pre-launch test mode)';
  end if;
  if to_regprocedure('public.grant_conference_reviewer(text)') is null then
    raise exception 'STEP B precondition failed: STEP A has not been applied';
  end if;
end $pre$;
SQL
emit $M/20261118000100_blind_review_and_reviewer_revocation.sql
emit $M/20261118000200_least_privilege_grants_and_role_policies.sql
cat <<'SQL'

do $post$
declare p record; bad text;
begin
  select * into p from _release_pre;
  if (select (demo_mode, registration_open, submissions_open, registration_deadline, abstract_deadline)
             is distinct from (p.demo_mode, p.registration_open, p.submissions_open, p.registration_deadline, p.abstract_deadline)
      from public.conference_settings where id = 1) then
    raise exception 'STEP B postcondition failed: launch settings changed';
  end if;
  if (select count(*) from public.registrations) <> p.registrations or (select count(*) from public.abstracts) <> p.abstracts
     or (select count(*) from public.reviews) <> p.reviews or (select count(*) from public.review_assignments) <> p.assignments
     or (select count(*) from public.user_roles) <> p.user_roles then
    raise exception 'STEP B postcondition failed: row counts changed';
  end if;
  -- No dangerous table privileges for client roles on the conference tables.
  select string_agg(r || ' ' || pr || ' ' || tb, ', ') into bad
  from unnest(array['anon','authenticated']) r,
       unnest(array['TRUNCATE','REFERENCES','TRIGGER']) pr,
       unnest(array['user_roles','registrations','abstracts','review_assignments','reviews','speakers','sessions','public_abstracts','conference_settings']) tb
  where has_table_privilege(r, 'public.' || tb, pr);
  if bad is not null then raise exception 'STEP B postcondition failed: client privileges remain: %', bad; end if;
  if has_column_privilege('authenticated', 'public.conference_settings', 'demo_mode', 'UPDATE')
     or has_column_privilege('anon', 'public.conference_settings', 'demo_mode', 'UPDATE') then
    raise exception 'STEP B postcondition failed: demo_mode is still updatable by a client role';
  end if;
  if exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'user_roles' and cmd in ('INSERT','UPDATE','DELETE','ALL')) then
    raise exception 'STEP B postcondition failed: a client write policy remains on user_roles';
  end if;
  if exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'abstracts' and policyname = 'abstract_owner_admin_reviewer_read') then
    raise exception 'STEP B postcondition failed: reviewer branch of the abstracts read policy remains';
  end if;
  -- Exact-signature function exposure.
  select string_agg(f, ', ') into bad from (
    select format('%s.%s(%s)', n.nspname, pp.proname, oidvectortypes(pp.proargtypes)) f
    from pg_proc pp join pg_namespace n on n.oid = pp.pronamespace
    where n.nspname = 'public' and has_function_privilege('authenticated', pp.oid, 'EXECUTE')
      and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = pp.oid and d.deptype = 'e')
      and pp.oid not in ('public.conference_reviewer_assignments()'::regprocedure, 'public.conference_reviewer_directory()'::regprocedure,
                         'public.find_conference_account(text)'::regprocedure, 'public.grant_conference_reviewer(text)'::regprocedure,
                         'public.revoke_conference_reviewer(uuid)'::regprocedure)) x;
  if bad is not null then raise exception 'STEP B postcondition failed: unapproved public functions executable by authenticated: %', bad; end if;
  select string_agg(format('%s.%s(%s)', n.nspname, pp.proname, oidvectortypes(pp.proargtypes)), ', ') into bad
  from pg_proc pp join pg_namespace n on n.oid = pp.pronamespace
  where n.nspname = 'public' and has_function_privilege('anon', pp.oid, 'EXECUTE')
    and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = pp.oid and d.deptype = 'e');
  if bad is not null then raise exception 'STEP B postcondition failed: public functions executable by anon: %', bad; end if;
  raise notice 'STEP B verified: settings and row counts unchanged; least-privilege grants, blind review and exact function exposure in place';
end $post$;
commit;
SQL
} > $OUT/step_b_apply.sql
echo "generated $OUT/step_a_apply.sql and $OUT/step_b_apply.sql"
